insert into public.campanhas (campanha, cliente, tipo, status, qtd, valor, prazo, pagamento, ativa, favorita)
select 'Exemplo: nome da campanha (pode apagar)', 'Nome do cliente', 'Conteúdo', 'Briefing',
       1, 0, current_date + 10, 'pendente', true, false
where not exists (select 1 from public.campanhas);


-- ---------------------------------------------------------------------
-- 12. AVISA O SUPABASE QUE A ESTRUTURA MUDOU
-- Faz o painel enxergar as tabelas novas na hora, sem esperar.
-- ---------------------------------------------------------------------
notify pgrst, 'reload schema';
