-- ---------------------------------------------------------------------
-- 1. QUEM É A DONA
-- Esta função responde "sim" só quando quem está logado é você.
-- Todas as trancas lá embaixo usam ela. Se um dia você trocar o e-mail
-- de login, troque só aqui e rode o arquivo de novo.
-- ---------------------------------------------------------------------
create or replace function public.eh_dona()
returns boolean
language sql
stable
as $$
  select coalesce(auth.jwt() ->> 'email', '') = 'comunidadecreatorstech@gmail.com';
$$;


-- ---------------------------------------------------------------------
-- 2. TABELA VIDEOS
-- Os vídeos que aparecem no portfólio. "ordem" decide quem vem primeiro,
-- "visivel" liga ou desliga o vídeo no site, e "destaque" é o número
-- que aparece em cima do card (ex: 2,4M views).
-- ---------------------------------------------------------------------
create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  criado_em timestamptz not null default now()
);
alter table public.videos add column if not exists titulo   text not null default '';
alter table public.videos add column if not exists link     text not null default '';
alter table public.videos add column if not exists nicho    text not null default '';
alter table public.videos add column if not exists formato  text not null default '';
alter table public.videos add column if not exists marca    text not null default '';
alter table public.videos add column if not exists destaque text not null default '';
alter table public.videos add column if not exists ordem    integer not null default 0;
alter table public.videos add column if not exists visivel  boolean not null default true;


-- ---------------------------------------------------------------------
-- 3. TABELA MARCAS
-- A sua base de contatos de empresa. Quem manda o formulário do site
-- entra aqui sozinho, como "lead".
-- ---------------------------------------------------------------------
create table if not exists public.marcas (
  id bigint generated by default as identity primary key,
  criado_em timestamptz not null default now()
);
alter table public.marcas add column if not exists nome           text not null default '';
alter table public.marcas add column if not exists instagram      text not null default '';
alter table public.marcas add column if not exists email          text not null default '';
alter table public.marcas add column if not exists telefone       text not null default '';
alter table public.marcas add column if not exists situacao       text not null default 'lead'
  check (situacao in ('lead', 'conversando', 'cliente', 'parada'));
alter table public.marcas add column if not exists obs            text not null default '';
alter table public.marcas add column if not exists ultimo_contato date;


-- ---------------------------------------------------------------------
-- 4. TABELA CALENDARIO
-- O que você vai gravar, editar e postar, dia a dia.
-- ---------------------------------------------------------------------
create table if not exists public.calendario (
  id bigint generated by default as identity primary key,
  criado_em timestamptz not null default now()
);
alter table public.calendario add column if not exists titulo text not null default '';
alter table public.calendario add column if not exists marca  text not null default '';
alter table public.calendario add column if not exists tipo   text not null default 'gravar'
  check (tipo in ('gravar', 'editar', 'postar'));
alter table public.calendario add column if not exists data   date not null default current_date;
alter table public.calendario add column if not exists status text not null default 'a fazer'
  check (status in ('a fazer', 'feito'));


-- ---------------------------------------------------------------------
-- 5. TABELA CAMPANHAS
-- Os seus trabalhos com marca. "valor" é o valor total da campanha e
-- "qtd" é quantos vídeos ela tem. Os status seguem o funil, nesta ordem.
-- ---------------------------------------------------------------------
create table if not exists public.campanhas (
  id bigint generated by default as identity primary key,
  criado_em timestamptz not null default now()
);
alter table public.campanhas add column if not exists campanha  text not null default '';
alter table public.campanhas add column if not exists cliente   text not null default '';
alter table public.campanhas add column if not exists tipo      text not null default 'Conteúdo'
  check (tipo in ('Conteúdo', 'Publicidade'));
alter table public.campanhas add column if not exists status    text not null default 'Briefing'
  check (status in ('Briefing', 'Roteiro', 'Aprovação Roteiro', 'Gravação', 'Edição', 'Aprovado', 'Entregue'));
alter table public.campanhas add column if not exists qtd       integer not null default 1;
alter table public.campanhas add column if not exists valor     numeric(12,2) not null default 0;
alter table public.campanhas add column if not exists prazo     date;
alter table public.campanhas add column if not exists pagamento text not null default 'pendente'
  check (pagamento in ('pendente', 'pago'));
alter table public.campanhas add column if not exists ativa     boolean not null default true;
alter table public.campanhas add column if not exists favorita  boolean not null default false;


-- ---------------------------------------------------------------------
-- 6. TABELA MARCADOS
-- Guarda o que você já marcou no checklist. Cada item tem uma chave de
-- texto (ex: "checklist:capa:0") e diz se está marcado ou não.
-- ---------------------------------------------------------------------
create table if not exists public.marcados (
  chave text primary key
);
alter table public.marcados add column if not exists marcado       boolean not null default true;
alter table public.marcados add column if not exists atualizado_em timestamptz not null default now();


-- ---------------------------------------------------------------------
-- 7. TABELA VISITAS
-- Cada vez que alguém abre o portfólio, entra uma linha aqui com a data,
-- a página e de onde a pessoa veio (Instagram, Google, direto...).
-- Não guarda nome, e-mail nem nada da pessoa.
-- ---------------------------------------------------------------------
create table if not exists public.visitas (
  id bigint generated by default as identity primary key
);
alter table public.visitas add column if not exists data   timestamptz not null default now();
alter table public.visitas add column if not exists pagina text not null default '';
alter table public.visitas add column if not exists origem text not null default '';
create index if not exists visitas_data_idx on public.visitas (data);


-- ---------------------------------------------------------------------
-- 8. LIGANDO A TRANCA (RLS) EM TODAS AS TABELAS
-- Com o RLS ligado, o banco começa fechado pra todo mundo. Só passa
-- quem tiver uma regra (policy) abrindo a porta, e as regras vêm logo abaixo.
-- ---------------------------------------------------------------------
alter table public.videos     enable row level security;
alter table public.marcas     enable row level security;
alter table public.calendario enable row level security;
alter table public.campanhas  enable row level security;
alter table public.marcados   enable row level security;
alter table public.visitas    enable row level security;


-- ---------------------------------------------------------------------
-- 9. PERMISSÕES BÁSICAS
-- Segunda camada de proteção. Primeiro tiramos tudo de quem não está
-- logado ("anon") e depois devolvemos só o mínimo:
--   * inserir em marcas (formulário do site)
--   * inserir em visitas (contador do site)
--   * ler videos (o site precisa mostrar os vídeos; a regra lá embaixo
--     deixa ler SÓ os que estão marcados como visíveis)
-- ---------------------------------------------------------------------
revoke all on public.videos, public.marcas, public.calendario,
              public.campanhas, public.marcados, public.visitas from anon;

grant select, insert, update, delete on public.videos, public.marcas, public.calendario,
              public.campanhas, public.marcados, public.visitas to authenticated;

grant insert on public.marcas, public.visitas to anon;
grant select on public.videos to anon;
grant usage, select on all sequences in schema public to anon, authenticated;


-- ---------------------------------------------------------------------
-- 10. AS REGRAS DE QUEM PASSA
-- Regra principal, em todas as tabelas: só a dona (você, logada) lê,
-- cria, edita e apaga. Qualquer outra pessoa, logada ou não, fica de fora.
-- ---------------------------------------------------------------------
drop policy if exists "dona faz tudo" on public.videos;
create policy "dona faz tudo" on public.videos
  for all to authenticated using (public.eh_dona()) with check (public.eh_dona());

drop policy if exists "dona faz tudo" on public.marcas;
create policy "dona faz tudo" on public.marcas
  for all to authenticated using (public.eh_dona()) with check (public.eh_dona());

drop policy if exists "dona faz tudo" on public.calendario;
create policy "dona faz tudo" on public.calendario
  for all to authenticated using (public.eh_dona()) with check (public.eh_dona());

drop policy if exists "dona faz tudo" on public.campanhas;
create policy "dona faz tudo" on public.campanhas
  for all to authenticated using (public.eh_dona()) with check (public.eh_dona());

drop policy if exists "dona faz tudo" on public.marcados;
create policy "dona faz tudo" on public.marcados
  for all to authenticated using (public.eh_dona()) with check (public.eh_dona());

drop policy if exists "dona faz tudo" on public.visitas;
create policy "dona faz tudo" on public.visitas
  for all to authenticated using (public.eh_dona()) with check (public.eh_dona());


-- Exceção 1: qualquer pessoa pode MANDAR o formulário do site.
-- Só entra como "lead", e com tamanho limitado pra ninguém encher o banco
-- de lixo. Quem mandou não consegue ler nada depois, nem o que mandou.
drop policy if exists "site manda formulario" on public.marcas;
create policy "site manda formulario" on public.marcas
  for insert to anon, authenticated
  with check (
    situacao = 'lead'
    and char_length(nome) between 1 and 200
    and char_length(email) <= 200
    and char_length(instagram) <= 200
    and char_length(telefone) <= 50
    and char_length(obs) <= 3000
  );

-- Exceção 2: qualquer pessoa pode REGISTRAR uma visita.
-- Também com tamanho limitado. Ler as visitas, só você.
drop policy if exists "site registra visita" on public.visitas;
create policy "site registra visita" on public.visitas
  for insert to anon, authenticated
  with check (
    char_length(pagina) <= 200
    and char_length(origem) <= 100
  );

-- Exceção 3 (necessária pro site funcionar): o portfólio precisa LER os
-- vídeos pra mostrar pros visitantes. Mas só os que estão com
-- "visivel" ligado. Vídeo escondido no painel não sai do banco.
drop policy if exists "site le videos visiveis" on public.videos;
create policy "site le videos visiveis" on public.videos
  for select to anon, authenticated
  using (visivel = true);


-- ---------------------------------------------------------------------
