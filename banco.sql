       'Nicho do vídeo', 'vídeo 9:16', 'Nome da marca', '0 views', 1, false
where not exists (select 1 from public.videos);

insert into public.marcas (nome, instagram, email, telefone, situacao, obs, ultimo_contato)
select 'Exemplo: nome da marca (pode apagar)', '@perfildamarca', 'contato@exemplo.com', '',
       'lead', 'Linha de exemplo, só pra mostrar o formato.', current_date
